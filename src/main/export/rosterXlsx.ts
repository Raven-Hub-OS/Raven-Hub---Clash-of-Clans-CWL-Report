import ExcelJS from 'exceljs'
import { APP_NAME } from '@shared/app'
import { sortPlayersByLeague } from '@shared/league'
import { seasonFileFragment } from '@shared/seasons'
import type { PlayerRow, RosterClan } from '@shared/types'

export interface RosterExportData {
  name: string
  seasonLabel: string
  sourceReportName: string
  clans?: RosterClan[]
  players: PlayerRow[]
}

export const ROSTER_COLUMNS: Array<{
  header: string
  key: keyof PlayerRow | 'order'
  width: number
  numberFormat?: string
}> = [
  { header: '#', key: 'order', width: 6, numberFormat: '0' },
  { header: 'Clan', key: 'clan', width: 20 },
  { header: 'Name', key: 'name', width: 24 },
  { header: 'Player Tag', key: 'tag', width: 15 },
  { header: 'TH', key: 'th', width: 6, numberFormat: '0' },
  { header: 'Wars Participated', key: 'warsParticipated', width: 17, numberFormat: '0' },
  { header: 'Attacks', key: 'attacks', width: 9, numberFormat: '0' },
  { header: 'Missed', key: 'missed', width: 9, numberFormat: '0' },
  { header: 'Attack Stars', key: 'attackStars', width: 12, numberFormat: '0' },
  { header: 'Avg Stars', key: 'avgStars', width: 10, numberFormat: '0.00' },
  { header: 'Destruction', key: 'destruction', width: 12, numberFormat: '0.00' },
  { header: 'Defenses', key: 'defenses', width: 10, numberFormat: '0' },
  { header: 'Defense Stars', key: 'defenseStars', width: 13, numberFormat: '0' },
  { header: 'Avg Defense', key: 'avgDefense', width: 12, numberFormat: '0.00' },
  { header: 'Reaches', key: 'reaches', width: 9, numberFormat: '0' },
  { header: 'Dips', key: 'dips', width: 9, numberFormat: '0' }
]

export function buildRosterWorkbook(roster: RosterExportData): ExcelJS.Workbook {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = APP_NAME
  workbook.lastModifiedBy = APP_NAME
  workbook.created = new Date()
  workbook.modified = new Date()
  workbook.title = `${roster.name} — CWL Roster`
  workbook.subject = 'Clash of Clans CWL roster'
  workbook.description = `Source report: ${roster.sourceReportName}. Data source: ClashKing (clashk.ing). Unofficial; not affiliated with or endorsed by Supercell.`
  workbook.keywords = 'Clash of Clans, CWL, roster, ClashKing'
  workbook.category = 'Clan management roster'

  const sheet = workbook.addWorksheet('Roster', {
    views: [{ state: 'frozen', ySplit: 1 }],
    properties: { defaultRowHeight: 19 }
  })

  sheet.columns = ROSTER_COLUMNS.map((column) => ({
    header: column.header,
    key: column.key,
    width: column.width
  }))

  const header = sheet.getRow(1)
  header.height = 27
  header.eachCell((cell) => {
    cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E2230' } }
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }
    cell.border = { bottom: { style: 'medium', color: { argb: 'FF2563EB' } } }
  })

  // One sheet and one table, with every clan grouped by league, strongest first.
  const orderedPlayers = sortPlayersByLeague(roster.players, roster.clans ?? [])

  orderedPlayers.forEach((player, index) => {
    const row = sheet.addRow({
      order: index + 1,
      clan: player.clan,
      name: player.name,
      tag: player.tag,
      th: player.th,
      warsParticipated: player.warsParticipated,
      attacks: player.attacks,
      missed: player.missed,
      attackStars: player.attackStars,
      avgStars: player.avgStars,
      destruction: player.destruction,
      defenses: player.defenses,
      defenseStars: player.defenseStars,
      avgDefense: player.avgDefense,
      reaches: player.reaches,
      dips: player.dips
    })
    row.height = 19

    row.eachCell((cell) => {
      cell.font = { name: 'Segoe UI', size: 10, color: { argb: 'FF1F2430' } }
      cell.alignment = { vertical: 'middle' }
      cell.border = { bottom: { style: 'hair', color: { argb: 'FFD9DCE3' } } }
    })

    for (const column of ROSTER_COLUMNS) {
      const cell = row.getCell(column.key)
      if (column.numberFormat) {
        cell.numFmt = column.numberFormat
        cell.alignment = { vertical: 'middle', horizontal: 'right' }
      } else if (column.key === 'tag') {
        cell.font = { name: 'Consolas', size: 10, color: { argb: 'FF1F2430' } }
      }
    }
  })

  const lastRow = Math.max(1, sheet.rowCount)
  sheet.autoFilter = `A1:P${lastRow}`
  sheet.pageSetup = {
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    margins: { left: 0.25, right: 0.25, top: 0.5, bottom: 0.5, header: 0.2, footer: 0.2 }
  }
  sheet.pageSetup.printTitlesRow = '1:1'
  sheet.headerFooter.oddFooter =
    `&LData: ClashKing — clashk.ing&CGenerated by ${APP_NAME}&RUnofficial — not affiliated with Supercell`

  return workbook
}

export async function writeRosterToFile(
  roster: RosterExportData,
  filePath: string
): Promise<void> {
  const workbook = buildRosterWorkbook(roster)
  await workbook.xlsx.writeFile(filePath)
}

export function buildRosterFileName(
  roster: Pick<RosterExportData, 'seasonLabel' | 'players'>
): string {
  const count = roster.players.length
  const players = count === 1 ? '1player' : `${count}players`
  return `RavenHub_Roster_${seasonFileFragment(roster.seasonLabel)}_${players}.xlsx`
}
