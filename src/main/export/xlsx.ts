import ExcelJS from 'exceljs'
import { APP_NAME } from '@shared/app'
import type { PlayerRow, ReportData } from '@shared/types'
import { seasonFileFragment } from '@shared/seasons'

export const PLAYER_COLUMNS: Array<{
  header: string
  key: keyof PlayerRow
  width: number
  numberFormat?: string
}> = [
  { header: 'Clan', key: 'clan', width: 20 },
  { header: 'Name', key: 'name', width: 24 },
  { header: '#', key: 'tag', width: 15 },
  { header: 'TH', key: 'th', width: 6, numberFormat: '0' },
  { header: 'Wars Participated', key: 'warsParticipated', width: 17, numberFormat: '0' },
  { header: 'Attacks', key: 'attacks', width: 9, numberFormat: '0' },
  { header: 'Missed', key: 'missed', width: 9, numberFormat: '0' },
  { header: 'Attack Stars', key: 'attackStars', width: 12, numberFormat: '0' },
  { header: 'Avg Stars', key: 'avgStars', width: 10, numberFormat: '0.00' },
  { header: 'Destruction', key: 'destruction', width: 12, numberFormat: '0.00' },
  { header: 'Defenses', key: 'defenses', width: 10, numberFormat: '0' },
  { header: 'Defense Stars', key: 'defenseStars', width: 13, numberFormat: '0' },
  { header: 'Avg Defense', key: 'avgDefense', width: 12, numberFormat: '0.00' },
  { header: 'Reaches', key: 'reaches', width: 9, numberFormat: '0' },
  { header: 'Dips', key: 'dips', width: 9, numberFormat: '0' }
]

const COLORS = {
  green: 'C6EFCE',
  amber: 'FFEB9C',
  red: 'FFC7CE',
  orange: 'F8CBAD',
  cyan: 'B7E4F5',
  gray: 'E7E6E6'
} as const

type FillColor = (typeof COLORS)[keyof typeof COLORS]

export function buildWorkbook(report: ReportData): ExcelJS.Workbook {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = APP_NAME
  workbook.lastModifiedBy = APP_NAME
  workbook.created = new Date(report.generatedAt)
  workbook.modified = new Date(report.generatedAt)
  workbook.title = `CWL ${report.seasonKey} — Player Report`
  workbook.subject = 'Clash of Clans Clan War Leagues player performance'
  workbook.description =
    'Data source: ClashKing (clashk.ing). Unofficial; not affiliated with or endorsed by Supercell.'
  workbook.keywords = 'Clash of Clans, CWL, ClashKing, clan war leagues'
  workbook.category = 'Clan management report'

  const sheet = workbook.addWorksheet('Players', {
    views: [{ state: 'frozen', ySplit: 1 }],
    properties: { defaultRowHeight: 19 }
  })

  sheet.columns = PLAYER_COLUMNS.map((column) => ({
    header: column.header,
    key: column.key,
    width: column.width
  }))

  const header = sheet.getRow(1)
  header.height = 27
  header.eachCell((cell) => {
    cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF1E2230' }
    }
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }
    cell.border = {
      bottom: { style: 'medium', color: { argb: 'FF2563EB' } }
    }
  })

  for (const player of report.players) {
    const row = sheet.addRow(toRowValues(player))
    row.height = 19

    row.eachCell((cell) => {
      cell.font = { name: 'Segoe UI', size: 10, color: { argb: 'FF1F2430' } }
      cell.alignment = { vertical: 'middle' }
      cell.border = {
        bottom: { style: 'hair', color: { argb: 'FFD9DCE3' } }
      }
    })

    for (const column of PLAYER_COLUMNS) {
      const cell = row.getCell(column.key)
      if (column.numberFormat) {
        cell.numFmt = column.numberFormat
        cell.alignment = { vertical: 'middle', horizontal: 'right' }
      } else if (column.key === 'tag') {
        cell.font = { name: 'Consolas', size: 10, color: { argb: 'FF1F2430' } }
      }
    }
  }

  const lastRow = Math.max(1, sheet.rowCount)
  sheet.autoFilter = `A1:O${lastRow}`
  sheet.pageSetup = {
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    margins: { left: 0.25, right: 0.25, top: 0.5, bottom: 0.5, header: 0.2, footer: 0.2 }
  }
  sheet.pageSetup.printTitlesRow = '1:1'
  sheet.headerFooter.oddFooter =
    `&LData: ClashKing — clashk.ing&CGenerated by ${APP_NAME}&RUnofficial — not affiliated with Supercell`

  if (lastRow >= 2) {
    addConditionalFormatting(sheet, lastRow)
  }

  return workbook
}

export async function writeWorkbookToFile(report: ReportData, filePath: string): Promise<void> {
  const workbook = buildWorkbook(report)
  await workbook.xlsx.writeFile(filePath)
}

export function buildFileName(report: ReportData): string {
  const count = report.clans.length
  const clans = count === 1 ? '1clan' : `${count}clans`
  return `RavenHub_CWL_${seasonFileFragment(report.season)}_${clans}.xlsx`
}

function toRowValues(player: PlayerRow): Record<string, string | number> {
  const values: Record<string, string | number> = {}
  for (const column of PLAYER_COLUMNS) {
    values[column.key] = player[column.key]
  }
  return values
}

function addConditionalFormatting(sheet: ExcelJS.Worksheet, lastRow: number): void {
  let priority = 1

  const add = (ref: string, formula: string, color: FillColor): void => {
    sheet.addConditionalFormatting({
      ref,
      rules: [
        {
          type: 'expression',
          formulae: [formula],
          priority: priority++,
          style: {
            fill: {
              type: 'pattern',
              pattern: 'solid',
              bgColor: { argb: `FF${color}` }
            }
          }
        }
      ]
    })
  }

  // Missed: 0 green, 1 amber, 2+ red.
  add(`G2:G${lastRow}`, '$G2=0', COLORS.green)
  add(`G2:G${lastRow}`, '$G2=1', COLORS.amber)
  add(`G2:G${lastRow}`, '$G2>=2', COLORS.red)

  // Attack stars compared with the maximum possible (wars * 3).
  add(`H2:H${lastRow}`, 'AND($E2>0,$H2=$E2*3,$G2=0)', COLORS.cyan)
  add(`H2:H${lastRow}`, 'AND($E2>0,$E2*3-$H2<=2)', COLORS.green)
  add(`H2:H${lastRow}`, 'AND($E2>0,$E2*3-$H2<=4)', COLORS.orange)
  add(`H2:H${lastRow}`, 'AND($E2>0,$E2*3-$H2>4)', COLORS.red)

  // Average attack stars.
  add(`I2:I${lastRow}`, '$I2=3', COLORS.cyan)
  add(`I2:I${lastRow}`, 'AND($I2>=2.85,$I2<3)', COLORS.green)
  add(`I2:I${lastRow}`, 'AND($I2>=2.5,$I2<2.85)', COLORS.amber)
  add(`I2:I${lastRow}`, 'AND($F2>0,$I2<2.5)', COLORS.red)

  // Destruction is a sum; compare it with attacks * 100.
  add(`J2:J${lastRow}`, 'AND($F2>0,$J2=$F2*100)', COLORS.cyan)
  add(`J2:J${lastRow}`, 'AND($F2>0,$J2>=$F2*98)', COLORS.green)
  add(`J2:J${lastRow}`, 'AND($F2>0,$J2>=$F2*97)', COLORS.amber)
  add(`J2:J${lastRow}`, 'AND($F2>0,$J2<$F2*97)', COLORS.red)

  // Average defense stars: lower is better, but 0 defenses means no data.
  add(`M2:M${lastRow}`, '$M2=0', COLORS.gray)
  add(`M2:M${lastRow}`, '$M2=3', COLORS.red)
  add(`M2:M${lastRow}`, 'AND($M2>=2.6,$M2<3)', COLORS.amber)
  add(`M2:M${lastRow}`, 'AND($K2>0,$M2<2.6)', COLORS.green)
}
